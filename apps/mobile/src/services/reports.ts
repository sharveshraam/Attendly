import * as FileSystem from 'expo-file-system/legacy';
import * as Sharing from 'expo-sharing';
import * as Print from 'expo-print';
import type { CourseAttendanceStats } from '@/types/domain';
import type { Course } from '@/types/domain';

export interface ReportCourse extends Course {
  stats: CourseAttendanceStats;
}

function csvEscape(value: string | number | null): string {
  const str = value === null ? '' : String(value);
  if (/[",\n]/.test(str)) return `"${str.replace(/"/g, '""')}"`;
  return str;
}

export function buildAttendanceCsv(courses: ReportCourse[]): string {
  const header = [
    'Course Code', 'Course Name', 'Conducted', 'Attended', 'Missed', 'Excused', 'Unmarked',
    'Attendance %', 'Target %', 'Bunk Allowance', 'Recovery Classes', 'Risk',
  ];
  const lines = [header.join(',')];
  for (const course of courses) {
    const s = course.stats;
    lines.push(
      [
        course.code ?? '', course.name, s.conducted, s.attended, s.missed, s.excused, s.unmarked,
        s.percent ?? '', s.target, s.bunkAllowance ?? '', s.recoveryClasses ?? '', s.risk,
      ]
        .map(csvEscape)
        .join(','),
    );
  }
  return lines.join('\n');
}

export async function shareCsv(filename: string, content: string): Promise<void> {
  const dir = FileSystem.cacheDirectory ?? FileSystem.documentDirectory;
  if (!dir) throw new Error('No writable directory available');
  const uri = `${dir}${filename}`;
  await FileSystem.writeAsStringAsync(uri, content, { encoding: FileSystem.EncodingType.UTF8 });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, { mimeType: 'text/csv', dialogTitle: 'Export attendance CSV' });
  } else {
    throw new Error('Sharing is not available on this device');
  }
}

export function buildReportHtml(title: string, subtitle: string, courses: ReportCourse[]): string {
  const rows = courses
    .map((course) => {
      const s = course.stats;
      const percent = s.percent === null ? '—' : `${s.percent}%`;
      const riskColor = s.risk === 'at_risk' ? '#D64545' : s.risk === 'warning' ? '#C77E14' : '#17A673';
      return `<tr>
        <td>${escapeHtml(course.name)}${course.code ? ` <span class="code">${escapeHtml(course.code)}</span>` : ''}</td>
        <td>${s.attended}/${s.conducted}</td>
        <td>${percent}</td>
        <td>${s.target}%</td>
        <td>${s.bunkAllowance ?? '—'}</td>
        <td>${s.recoveryClasses ?? '—'}</td>
        <td style="color:${riskColor};font-weight:600">${s.risk.replace('_', ' ')}</td>
      </tr>`;
    })
    .join('');

  return `<!DOCTYPE html>
<html><head><meta charset="utf-8" />
<style>
  body { font-family: -apple-system, Roboto, sans-serif; color: #172033; padding: 32px; }
  h1 { font-size: 24px; margin: 0 0 4px; }
  .sub { color: #69758D; margin: 0 0 24px; font-size: 13px; }
  table { width: 100%; border-collapse: collapse; font-size: 12px; }
  th { text-align: left; background: #F6F7FB; padding: 10px 8px; border-bottom: 2px solid #E4E8F2; }
  td { padding: 10px 8px; border-bottom: 1px solid #EEF0F7; }
  .code { color: #69758D; font-size: 11px; }
  .footer { margin-top: 24px; color: #98A1B5; font-size: 11px; }
</style></head>
<body>
  <h1>${escapeHtml(title)}</h1>
  <p class="sub">${escapeHtml(subtitle)}</p>
  <table>
    <thead><tr><th>Course</th><th>Attended/Conducted</th><th>Attendance</th><th>Target</th><th>Can miss</th><th>To recover</th><th>Status</th></tr></thead>
    <tbody>${rows}</tbody>
  </table>
  <p class="footer">Generated by Attendly. Unmarked sessions are excluded from percentages. Estimates are labelled where schedule data is incomplete.</p>
</body></html>`;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export async function sharePdf(title: string, subtitle: string, courses: ReportCourse[]): Promise<void> {
  const html = buildReportHtml(title, subtitle, courses);
  const { uri } = await Print.printToFileAsync({ html, base64: false });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, { mimeType: 'application/pdf', dialogTitle: 'Export attendance report', UTI: 'com.adobe.pdf' });
  } else {
    throw new Error('Sharing is not available on this device');
  }
}
